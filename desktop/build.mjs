// Build the AEGIS Hermes Desktop plugin: src/plugin.tsx -> plugin.js (one ESM file).
//
//   node plugins/aegis/desktop/build.mjs      (needs esbuild + three, see ../dashboard/package.json)
//
// Hermes Desktop loads disk plugins uncompiled and lets them import only
// `@hermes/plugin-sdk`, `react` and `react/jsx-runtime`, so those stay external
// and everything else — the shared Mission Control view (with the canvas orb;
// three.js is left out because the catalog lint forbids its prototype writes),
// the CSS, the artwork and the Regalia fonts — is inlined into the single file.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dashboard = join(here, "..", "dashboard");
const fontsDir = join(here, "..", "assets", "fonts");

// Regalia's faces as data URLs: the desktop renderer can't fetch plugin files by path.
const face = (family, file, style) =>
  `@font-face { font-family: "${family}"; font-style: ${style}; font-weight: 400; font-display: swap;
  src: url(data:font/ttf;base64,${readFileSync(join(fontsDir, file)).toString("base64")}) format("truetype"); }`;
writeFileSync(join(here, "src", "fonts.css"), [
  "/* Generated by build.mjs from assets/fonts (SIL OFL 1.1, unmodified). */",
  face("Great Vibes", "GreatVibes-Regular.ttf", "normal"),
  face("IM Fell English", "IMFeENrm28P.ttf", "normal"),
  face("IM Fell English", "IMFeENit28P.ttf", "italic"),
].join("\n"));

const require = createRequire(join(dashboard, "package.json"));
// esbuild and three are installed once, in ../dashboard (npm --prefix plugins/aegis/dashboard install).
const { build } = require("esbuild");
const alias = {};
try { require.resolve("three"); } catch {
  const vendored = join(dashboard, "vendor", "three.module.js");
  if (existsSync(vendored)) alias.three = vendored;
}

await build({
  absWorkingDir: here,
  entryPoints: ["src/plugin.tsx"],
  outfile: "plugin.js",
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["chrome120"],
  minify: true,
  jsx: "automatic",
  external: ["@hermes/plugin-sdk", "react", "react/jsx-runtime"],
  loader: { ".jpg": "dataurl", ".png": "dataurl", ".css": "text" },
  nodePaths: [join(dashboard, "node_modules")],
  alias,
  legalComments: "eof",
  logLevel: "info",
});
